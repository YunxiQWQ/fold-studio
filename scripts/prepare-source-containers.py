"""Convert the selected CC0 glTF geometry to a small offline module (no textures).
Input: Poly Haven glTF + bin downloaded from the official files API.
Usage: python scripts/prepare-source-containers.py ../research-upstream/selected-20261021
"""
import json,struct,sys,pathlib,hashlib

root=pathlib.Path(sys.argv[1]); output={}
def read_accessor(doc,binary,index):
    a=doc['accessors'][index];view=doc['bufferViews'][a['bufferView']]
    count={'SCALAR':1,'VEC2':2,'VEC3':3,'VEC4':4}[a['type']]
    fmt={5126:'f',5125:'I',5123:'H',5121:'B'}[a['componentType']]
    size=struct.calcsize('<'+fmt*count);stride=view.get('byteStride',size)
    start=view.get('byteOffset',0)+a.get('byteOffset',0)
    return [struct.unpack_from('<'+fmt*count,binary,start+i*stride) for i in range(a['count'])]

for asset,mesh_names in [('russian_food_cans_01',[(0,'salt-pack'),(1,'food-tin-tall'),(2,'food-tin-low')]),('cleaner_tin_01',[(0,'screw-metal-tin')])]:
    folder=root/asset;data=(folder/(asset+'.gltf')).read_bytes();doc=json.loads(data)
    binary=(folder/doc['buffers'][0]['uri']).read_bytes()
    for mi,key in mesh_names:
        p=doc['meshes'][mi]['primitives'][0]
        pos=read_accessor(doc,binary,p['attributes']['POSITION']);norm=read_accessor(doc,binary,p['attributes']['NORMAL'])
        indices=[v[0] for v in read_accessor(doc,binary,p['indices'])]
        lo=[min(p[i] for p in pos) for i in range(3)];hi=[max(p[i] for p in pos) for i in range(3)]
        diameter=max(hi[0]-lo[0],hi[2]-lo[2]);height=hi[1]-lo[1];cx=(lo[0]+hi[0])/2;cz=(lo[2]+hi[2])/2
        normalized=[[round((x-cx)/diameter,7),round((y-lo[1])/height,7),round((z-cz)/diameter,7)] for x,y,z in pos]
        output[key]={'source':f'https://polyhaven.com/a/{asset}','license':'CC0-1.0','sourceSHA256':hashlib.sha256(data+binary).hexdigest(),'originalSizeMM':[round((hi[i]-lo[i])*1000,4) for i in range(3)],'positions':sum(normalized,[]),'normals':[round(x,6) for n in norm for x in n],'indices':indices}

path=pathlib.Path('src/source-containers.generated.js')
path.write_text('// Selected Poly Haven geometry, CC0-1.0. See THIRD_PARTY_NOTICES.md.\n// Generated by scripts/prepare-source-containers.py; no original label textures.\nexport const SOURCE_CONTAINERS='+json.dumps(output,separators=(',',':'))+';\n',encoding='utf-8')
print(f'{len(output)} source meshes, {path.stat().st_size} bytes')
